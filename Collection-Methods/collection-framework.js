/* ---------- animate bars ---------- */
function animate(){
  $$('.fill').forEach(f=>{ const w=f.dataset.w+'%'; if(reduce){f.style.width=w;} else {requestAnimationFrame(()=>{f.style.width=w;});} });
  $$('.stack .seg').forEach(s=>{
    const k=s.dataset.k, i=s.dataset.i, a=s.dataset.a;
    const v = (i!=null) ? OUTCOMES[k].v[i] : AGEING[k].v[a];
    const w = Math.max(v,0.35)+'%';
    if(reduce){s.style.width=w;} else {requestAnimationFrame(()=>{s.style.width=w;});}
  });
}
if('IntersectionObserver' in window && !reduce){
  const io=new IntersectionObserver((es)=>{es.forEach(e=>{if(e.isIntersecting){animate(); io.disconnect();}})},{threshold:.15});
  $$('.fig').forEach(f=>io.observe(f));
  setTimeout(animate, 600);
} else animate();

