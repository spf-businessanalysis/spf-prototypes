/* ---------- helpers ---------- */
function table(el, head, rows, opts={}){
  const numCols = opts.num || [];
  const cap = opts.caption ? `<caption>${opts.caption}</caption>` : '';
  const thead = `<thead><tr>${head.map((h,i)=>`<th${numCols.includes(i)?' class="n"':''} scope="col">${h}</th>`).join('')}</tr></thead>`;
  const tbody = `<tbody>${rows.map(r=>{
    const cls = (opts.totalRow!=null && rows.indexOf(r)===opts.totalRow) ? ' class="total"' : '';
    return `<tr${cls}>${r.map((c,i)=> i===0 && opts.rowHeader
      ? `<th scope="row">${c}</th>`
      : `<td${numCols.includes(i)?' class="n"':''}>${c}</td>`).join('')}</tr>`;
  }).join('')}</tbody>`;
  el.innerHTML = `<table>${cap}${thead}${tbody}</table>`;
}
function list(el, items){ el.innerHTML = items.map(i=>`<li>${i}</li>`).join(''); }

/* ---------- tooltip ---------- */
const tip = $('#tip');
function showTip(e, html){
  tip.innerHTML = html; tip.classList.add('on');
  const r = tip.getBoundingClientRect();
  let x = e.clientX - r.width/2, y = e.clientY - r.height - 12;
  x = Math.max(8, Math.min(x, innerWidth - r.width - 8));
  if (y < 8) y = e.clientY + 16;
  tip.style.left = x+'px'; tip.style.top = y+'px';
}
function hideTip(){ tip.classList.remove('on'); }

