  const io = new IntersectionObserver(es=>{
    es.forEach(e=>{ if(e.isIntersecting){ links.forEach(a=>a.classList.remove('on')); links.get(e.target.id)?.classList.add('on'); } });
  }, {rootMargin:'-90px 0px -70% 0px', threshold:0});
